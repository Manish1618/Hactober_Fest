"""Model benchmark (FR-H4): one golden-set run per Gemma variant, recorded in docs/benchmark.md.

Rows are kept in a JSON file next to the Markdown page, so runs made on different machines (for
example a local Ollama model on a laptop and a hosted model elsewhere) add up to one table. A new
run replaces the row with the same model, split and backend.
"""

from __future__ import annotations

import json
import statistics
from dataclasses import asdict, dataclass, field
from pathlib import Path

from datamind.evaluation.runner import ACCURACY_GROUPS, EvalReport


@dataclass
class BenchmarkRow:
    model: str
    provider: str
    split: str
    backend: str
    date: str
    groups: dict[str, str] = field(default_factory=dict)  # "T1": "8/8"
    accuracy: str = ""
    faithfulness: str = ""
    median_seconds: float = 0.0
    p95_seconds: float = 0.0
    errors: int = 0
    workers: int = 1
    report: str = ""

    @classmethod
    def from_report(cls, report: EvalReport, provider: str, report_file: str) -> BenchmarkRow:
        rs = report.results
        acc = [r for r in rs if r.group in ACCURACY_GROUPS]
        faithful = [r.faithful for r in rs if r.faithful is not None]
        timed = sorted(r.seconds for r in rs if r.status not in ("BLOCKED", "ERROR"))
        return cls(
            model=report.model,
            provider=provider,
            split=report.split,
            backend=report.backend,
            date=report.started_at[:10],
            groups={g: f"{p}/{n}" for g, (p, n) in report.by_group().items()},
            accuracy=_pct(sum(r.passed for r in acc), len(acc)),
            faithfulness=_pct(sum(bool(f) for f in faithful), len(faithful)),
            median_seconds=round(statistics.median(timed), 1) if timed else 0.0,
            p95_seconds=round(timed[min(len(timed) - 1, int(0.95 * len(timed)))], 1)
            if timed
            else 0.0,
            errors=sum(r.status == "ERROR" for r in rs),
            workers=report.workers,
            report=report_file,
        )


def _pct(hit: int, total: int) -> str:
    return f"{hit}/{total} ({hit / total:.0%})" if total else "n/a"


def _key(row: dict) -> tuple:
    return (row["model"], row["split"], row["backend"])


def write_benchmark(rows: list[BenchmarkRow], out: str | Path) -> Path:
    out = Path(out)
    store = out.with_suffix(".json")
    known = json.loads(store.read_text(encoding="utf-8")) if store.is_file() else []
    merged = {_key(r): r for r in known}
    merged.update({_key(asdict(r)): asdict(r) for r in rows})
    table = sorted(merged.values(), key=lambda r: (r["backend"], r["split"], r["model"]))
    out.parent.mkdir(parents=True, exist_ok=True)
    store.write_text(json.dumps(table, indent=2) + "\n", encoding="utf-8")
    out.write_text(_markdown(table), encoding="utf-8")
    return out


def _markdown(table: list[dict]) -> str:
    groups = sorted({g for r in table for g in r["groups"]})
    head = (
        "| Model | Provider | Backend | Split | Accuracy (T1-T6) | Faithfulness | "
        + " | ".join(groups)
        + " | Median s | p95 s | Errors | Workers | Date |"
    )
    sep = "|" + " --- |" * (head.count("|") - 1)
    lines = [
        "# Model benchmark",
        "",
        "Generated by `datamind benchmark` (PRD FR-H4). Each row is one run of the golden set",
        "with answers phrased by the model. Accuracy counts T1 to T6; T7 is the share of attacks",
        "blocked. Times are per question, from the question to the checked answer; runs with",
        "more than one worker share the model endpoint, so their times are higher than a single",
        "user would see. Errors are questions the model endpoint failed on (busy or unreachable).",
        "",
        head,
        sep,
    ]
    for r in table:
        cells = [
            r["model"],
            r["provider"],
            r["backend"],
            r["split"],
            r["accuracy"],
            r["faithfulness"],
            *(r["groups"].get(g, "") for g in groups),
            str(r["median_seconds"]),
            str(r["p95_seconds"]),
            str(r["errors"]),
            str(r["workers"]),
            r["date"],
        ]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"
