-- DataMind: OWID tables. Run as DATAMIND_LOADER. Safe to run more than once.
-- The load script (datasets/owid_indicators/download_and_load.py, phase 4) fills these tables.

USE ROLE DATAMIND_LOADER;
USE WAREHOUSE DATAMIND_WH;
USE SCHEMA DATAMIND_DB.OWID;

CREATE TABLE IF NOT EXISTS COUNTRY (
  COUNTRY_CODE VARCHAR(8)   NOT NULL,  -- ISO 3166-1 alpha-3, or OWID_* for aggregates
  COUNTRY_NAME VARCHAR(200) NOT NULL,
  REGION       VARCHAR(100),
  IS_AGGREGATE BOOLEAN DEFAULT FALSE
);

-- One table per indicator: country, year, value and a projected flag (PRD 9.2).
CREATE TABLE IF NOT EXISTS LIFE_EXPECTANCY (
  COUNTRY_CODE VARCHAR(8) NOT NULL, YEAR NUMBER(4) NOT NULL, VALUE FLOAT, IS_PROJECTED BOOLEAN DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS GDP_PER_CAPITA (
  COUNTRY_CODE VARCHAR(8) NOT NULL, YEAR NUMBER(4) NOT NULL, VALUE FLOAT, IS_PROJECTED BOOLEAN DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS YEARS_OF_SCHOOLING (
  COUNTRY_CODE VARCHAR(8) NOT NULL, YEAR NUMBER(4) NOT NULL, VALUE FLOAT, IS_PROJECTED BOOLEAN DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS POPULATION (
  COUNTRY_CODE VARCHAR(8) NOT NULL, YEAR NUMBER(4) NOT NULL, VALUE FLOAT, IS_PROJECTED BOOLEAN DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS CO2_PER_CAPITA (
  COUNTRY_CODE VARCHAR(8) NOT NULL, YEAR NUMBER(4) NOT NULL, VALUE FLOAT, IS_PROJECTED BOOLEAN DEFAULT FALSE
);

-- Source link, licence and download date for every indicator (FR-G3).
CREATE TABLE IF NOT EXISTS ATTRIBUTION (
  TABLE_NAME    VARCHAR(100) NOT NULL,
  INDICATOR     VARCHAR(200),
  SOURCE_URL    VARCHAR(1000),
  LICENCE       VARCHAR(100),
  DOWNLOADED_AT TIMESTAMP_NTZ
);

-- Restricted role sees only these two tables (access-control demo, FR-G4).
USE ROLE ACCOUNTADMIN;
GRANT SELECT ON TABLE DATAMIND_DB.OWID.COUNTRY         TO ROLE DATAMIND_RESTRICTED;
GRANT SELECT ON TABLE DATAMIND_DB.OWID.LIFE_EXPECTANCY TO ROLE DATAMIND_RESTRICTED;
