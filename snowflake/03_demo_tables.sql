-- DataMind: changeable demo tables for the data-change test (PRD US-12, FR-K5, test group T8).
-- Run as ACCOUNTADMIN. Safe to run more than once.
--
-- ORDERS_BASE and CUSTOMER_BASE are copies of the TPC-H sample (shared databases cannot be
-- cloned). ORDERS and CUSTOMER are zero-copy clones of them: the test edits the clones and
-- re-clones them afterwards. The application reads them as DATAMIND_READER like any other table.
-- DATAMIND_LOADER is granted to DATAMIND_APP only so the test can make its edits; the
-- application always connects with the read-only role named in the dataset config.

USE ROLE ACCOUNTADMIN;

CREATE SCHEMA IF NOT EXISTS DATAMIND_DB.DEMO;
GRANT ALL ON SCHEMA DATAMIND_DB.DEMO TO ROLE DATAMIND_LOADER;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE DATAMIND_LOADER;
GRANT USAGE ON SCHEMA DATAMIND_DB.DEMO TO ROLE DATAMIND_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA DATAMIND_DB.DEMO TO ROLE DATAMIND_READER;
GRANT ROLE DATAMIND_LOADER TO USER DATAMIND_APP;

USE ROLE DATAMIND_LOADER;
USE WAREHOUSE DATAMIND_WH;
USE SCHEMA DATAMIND_DB.DEMO;

CREATE TABLE IF NOT EXISTS ORDERS_BASE AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS;
CREATE TABLE IF NOT EXISTS CUSTOMER_BASE AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER;
CREATE OR REPLACE TABLE ORDERS CLONE ORDERS_BASE;
CREATE OR REPLACE TABLE CUSTOMER CLONE CUSTOMER_BASE;

-- Future grants cover tables created after them; these lines cover tables made before.
GRANT SELECT ON ALL TABLES IN SCHEMA DATAMIND_DB.DEMO TO ROLE DATAMIND_READER;
